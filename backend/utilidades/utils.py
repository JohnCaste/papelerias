
def obtenerMes(mesInt):
    if mesInt == 1:
        return 'enero'
    elif mesInt == 2:
        return 'febrero'
    elif mesInt == 3:
        return 'marzo'
    elif mesInt == 4:
        return 'abril'
    elif mesInt == 5:
        return 'mayo'
    elif mesInt == 6:
        return 'junio'
    elif mesInt == 7:
        return 'julio'
    elif mesInt == 8:
        return 'agosto'
    elif mesInt == 9:
        return 'septiembre'
    elif mesInt == 10:
        return 'octubre'
    elif mesInt == 11:
        return 'noviembre'
    elif mesInt == 12:
        return 'diciembre'
    else:
        return 'Error'